-- 057: commercial price audit trail and sales pipeline.
-- Safe to re-run. Platform-admin-only records; no customer operational data is changed.
BEGIN;

CREATE TABLE IF NOT EXISTS public.app_commercial_price_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type text NOT NULL CHECK (entity_type IN ('license_plan','module','other_concept')),
  entity_key text NOT NULL,
  display_name text NOT NULL,
  previous_values jsonb NOT NULL DEFAULT '{}'::jsonb,
  new_values jsonb NOT NULL DEFAULT '{}'::jsonb,
  actor_user_id uuid,
  created_at timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS app_commercial_price_history_created_idx
  ON public.app_commercial_price_history (created_at DESC);
CREATE INDEX IF NOT EXISTS app_commercial_price_history_entity_idx
  ON public.app_commercial_price_history (entity_type, entity_key, created_at DESC);
ALTER TABLE public.app_commercial_price_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_commercial_price_history FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS mattsystem_commercial_price_history_admin_all
  ON public.app_commercial_price_history;
CREATE POLICY mattsystem_commercial_price_history_admin_all
  ON public.app_commercial_price_history FOR ALL TO PUBLIC
  USING (public.app_is_platform_admin())
  WITH CHECK (public.app_is_platform_admin());

CREATE TABLE IF NOT EXISTS public.app_sales_pipeline (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  prospect_name varchar(120) NOT NULL,
  business_name varchar(160) NOT NULL DEFAULT '',
  email varchar(254) NOT NULL DEFAULT '',
  phone varchar(50) NOT NULL DEFAULT '',
  industry varchar(80) NOT NULL DEFAULT '',
  source varchar(80) NOT NULL DEFAULT '',
  stage varchar(24) NOT NULL DEFAULT 'new'
    CHECK (stage IN ('new','contacted','meeting','proposal','negotiation','won','lost')),
  estimated_value numeric(14,0) NOT NULL DEFAULT 0 CHECK (estimated_value >= 0),
  expected_close_date date,
  next_follow_up_at timestamptz,
  notes text NOT NULL DEFAULT '',
  created_by uuid NOT NULL,
  updated_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS app_sales_pipeline_stage_idx
  ON public.app_sales_pipeline (stage, updated_at DESC);
CREATE INDEX IF NOT EXISTS app_sales_pipeline_follow_up_idx
  ON public.app_sales_pipeline (next_follow_up_at)
  WHERE next_follow_up_at IS NOT NULL;
ALTER TABLE public.app_sales_pipeline ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_sales_pipeline FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS mattsystem_sales_pipeline_admin_all
  ON public.app_sales_pipeline;
CREATE POLICY mattsystem_sales_pipeline_admin_all
  ON public.app_sales_pipeline FOR ALL TO PUBLIC
  USING (public.app_is_platform_admin())
  WITH CHECK (public.app_is_platform_admin());

INSERT INTO public.schema_migrations(version)
VALUES ('057_commercial_price_history_and_sales_pipeline')
ON CONFLICT (version) DO NOTHING;

COMMIT;
